"""입력에 섞지 않고 사람이 열어 볼 날짜별 안내를 만든다."""
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent


def read_lines(path):
    return [json.loads(s) for s in path.read_text(encoding="utf-8").splitlines()]


def main():
    days = read_lines(ROOT / "검토용" / "날짜별설정.jsonl")
    count = sum(d["가전신호수"] for d in days)
    frames = sum(d["관찰줄수"] for d in days)
    guide = [
        "# 클로이봇과 한 사람의 28일",
        f"2026년 10월 12일 월요일부터 11월 8일 일요일까지 한국 시각으로 구성한 가상 생활 기록입니다. "
        f"가전 신호 {count:,}건 주변에서 로봇이 볼 수 있었던 장면 {frames:,}줄을 담았습니다. 날씨와 센서 값도 합성했습니다.",
        "## 하루씩 넣는 방법",
        "먼저 [10월 12일 입력 폴더](일별입력/2026-10-12)를 여세요. 날짜 폴더 하나가 하루치입니다. "
        "모델에 시간순으로 보낼 때는 해당 시각까지의 가전 신호, 관찰, 날씨와 실내온도를 읽습니다. "
        "첫날 밤까지 모은 기록에서 만든 도움 규칙은 다음 날부터 적용합니다.",
        "Python이 설치되어 있다면 압축을 푼 폴더에서 아래 명령으로 첫날을 시간순으로 읽을 수 있습니다. "
        "한 줄이 한 시점의 한 자료입니다. 다른 날을 읽으려면 명령 끝의 날짜를 바꾸세요. "
        "이 명령은 자료를 읽어 출력하는 도구이며 학습기를 호출하지 않습니다.",
        "```powershell\npython 하루읽기.py 2026-10-12\n```",
        "| 날짜 폴더 안의 파일 | 담긴 내용 |\n|---|---|\n"
        "| 가전신호.jsonl | 발생 시각, 조작 주체, 기기, 변한 항목과 값. 한 줄에 사건 한 건 |\n"
        "| 관찰.txt | 시각 / 로봇 위치 / 그 위치에서 관찰한 내용. 이름이 같은 위치가 이어져도 매 시점을 유지 |\n"
        "| weather.json | 매시 정각의 합성 날씨와 외기온 |\n"
        "| 실내온도.jsonl | 30분마다 에어컨이 보고한 실내온도. 온도 갱신은 관찰 수집을 시작하지 않음 |",
        "## 4초 기록을 읽는 기준",
        "신호 시각을 포함합니다. 기계가 낸 신호는 그 시각부터 10분 뒤까지 151시점, 사람이 조작한 신호는 "
        "10분 전부터 10분 뒤까지 301시점입니다. 신호와 관찰의 시각을 4초 단위로 맞췄습니다. 두 구간이 겹친 시각은 "
        "같은 장면이므로 하루 파일에 한 번만 저장했습니다. 구간 밖의 시간에는 카메라 기록이 없습니다.",
        "예를 들어 10월 28일에는 세탁기 완료 후 12분 16초가 지나 사람이 문을 엽니다. 완료 신호 뒤 10분만 보고 "
        "‘빨래를 꺼내지 않았다’고 단정하기는 이릅니다. 뒤이어 발생한 사람의 문 열림 신호에서 다시 관찰할 수 있습니다. "
        "특정 시각에 관찰이 없거나 물건이 가려진 경우에는 행동 여부를 알 수 없습니다.",
        "## 도움을 시험할 때",
        "여기에는 사람이 직접 한 일이 들어 있습니다. 재생 중 로봇이 어떤 명령을 냈다면 그 시각과 명령을 별도의 "
        "실험 결과에 남기세요. 사용자가 일을 건너뛰거나 도움을 받아들이는 결과는 별도로 시뮬레이션해야 확인할 수 있습니다. "
        "손님 방문이나 한 번의 분갈이처럼 드문 사건도 일상에 포함했습니다.",
        "아래 날짜 안내와 검토용 폴더에는 그날 뒤에 벌어질 일도 적혀 있습니다. 날짜별 학습과 재생의 입력은 일별입력 폴더에서 읽으세요.",
        "## 날짜별로 찾아보기",
    ]
    table = ["| 날짜 | 가전 신호 | 관찰 줄 수 | 찾아볼 장면 |", "|---|---:|---:|---|"]
    for d in days:
        date = d["날짜"]
        notes = [s["내용"] for s in d["작성자메모"] if not s["내용"].startswith(("08시 생활 알림", "저녁 쟁반"))]
        if d["저녁손님"]:
            notes.insert(0, "방문객과 주방 식탁에서 식사.")
        if d["외식설정"]:
            notes.insert(0, "외식으로 집 안 저녁 식사 장면이 없는 날.")
        if not notes:
            notes = ["집에 있는 동안 가전 조작과 주변의 4초 관찰을 확인할 수 있습니다."]
        table.append(f"| [{date} ({d['요일']})](일별입력/{date}/관찰.txt) | {d['가전신호수']:,} | {d['관찰줄수']:,} | {' '.join(notes[:3])} |")
    guide.extend(["\n".join(table),
                  "검토용/수집구간.jsonl에는 각 신호의 식별번호와 해당 관찰의 첫 시각·끝 시각이 있습니다. "
                  "생성도구/verify.py를 실행하면 28일치 파일을 다시 읽어 검사합니다."])
    (ROOT / "시작안내.md").write_text("\n\n".join(guide) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
