    scene(day, start, "침실", [(100, "사용자가 옷걸이에서 옷을 꺼내 팔에 걸고 방문 쪽으로 걸어간다.")])
    day.signal(start + 108, "사람", "침실 조명", "전원", "꺼짐")
    day.see(start + 108, "복도", "침실 불이 꺼지고 사용자가 욕실 쪽 복도를 지난다.")
