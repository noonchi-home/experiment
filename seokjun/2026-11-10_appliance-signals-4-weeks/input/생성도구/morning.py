def medicine(day, alarm, prepare):
    day.signal(alarm, "기계", "스마트 스피커", "생활 알림", "울림")
    if prepare > alarm:
        day.note(alarm, "08시 생활 알림이 울렸다. 약통을 만지는 모습이 나타나는 시각은 더 늦다.")
    if prepare < alarm:
        raise ValueError("생활 알림보다 이른 약통 장면")
    scene(day, prepare, "주방", [
        (0, "사용자가 식탁 옆 작은 서랍을 연다."),
        (12, "사용자가 요일 글자가 인쇄된 약통을 식탁에 내려놓는다."),
        (20, "사용자가 약통 윗면의 작은 뚜껑 하나를 젖힌다."),
    ])
    if day.n % 4 == 0:
        scene(day, prepare, "주방", [
            (32, "사용자가 식탁 위에 이미 있던 물컵을 잡는다."),
            (40, "사용자가 물컵을 입 가까이 들고 약통에서 손을 뗀다."),
        ])
    else:
        scene(day, prepare, "주방", [
            (32, "사용자가 컵걸이에서 작은 유리컵을 빼고 정수기 앞에 댄다."),
            (48, "사용자가 물이 담긴 컵을 들어 식탁 쪽으로 가져온다."),
            (60, "사용자가 컵을 입에 댄다. 아래쪽은 식탁 모서리에 가려져 있다."),
        ])
    scene(day, prepare, "주방", [
        (76, "사용자가 컵을 내려놓고 약통 뚜껑을 손끝으로 누른다."),
        (88, "사용자가 약통을 작은 서랍에 넣고 서랍을 밀어 닫는다."),
        (104, "식탁에 물컵이 놓여 있다. 사용자가 한 손으로 휴대전화를 본다."),
    ])


