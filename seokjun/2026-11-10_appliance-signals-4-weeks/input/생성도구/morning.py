    if day.n in {4, 18, 27}:
        scene(day, start, "침실", [
            (44, "사용자가 이불 끝만 한쪽으로 밀고 침대에서 내려선다."),
            (60, "베개 밑에 이불 모서리가 끼어 있다. 사용자는 의자에 걸어 둔 옷을 집는다."),
        ])
