"""한 집의 아침 장면. 시각은 자정 이후의 초, 현관문 밖과 욕실 안은 보이지 않는다."""


def scene(day, start, location, changes):
    for offset, description in changes:
        day.see(start + offset, location, description)


def wake_up(day, start):
    rng = day.rng
    bed = "얇은 회색 이불" if day.n < 16 else "회색 누빔이불"
    day.see(6 * 3600, "침실", f"침대 위에 {bed}이 덮여 있다. 베개 옆에는 안경집이 놓여 있다.")
    if day.work in {"출근", "재택"}:
        day.signal(start, "기계", "침실 알람시계", "알림", "울림")
    scene(day, start, "침실", [
        (0, "침대 머리 쪽으로 손이 나와 협탁 위를 더듬는다."),
        (8, "사용자가 베개에서 상체를 일으키고 협탁 쪽으로 손을 뻗는다."),
        (16, "사용자가 침대 가장자리에 앉아 안경을 쓴다."),
    ])
    if day.work in {"출근", "재택"}:
        day.signal(start + 12, "사람", "침실 알람시계", "알림", "해제")
    day.signal(start + 32, "사람", "침실 조명", "전원", "켜짐")
