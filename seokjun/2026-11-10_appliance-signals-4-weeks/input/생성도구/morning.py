    if coffee:
        menu = "빵" if day.n in {1, 6, 11, 17, 22, 26} else "요거트"
    elif day.n in {5, 18} and day.work == "출근":
        menu = "간단히"
    if hair:
        dry_hair(day, start)
    else:
        day.see(start - 40, "복도", "욕실 문이 열리고 사용자가 수건으로 손을 훔치며 주방 쪽으로 나온다.")
