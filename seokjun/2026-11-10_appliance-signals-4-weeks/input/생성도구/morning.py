def at_home(day, t):
    if day.work == "재택":
        scene(day, t, "작업방", [
            (0, "사용자가 책상 앞에 앉는다. 가방은 의자 옆 고리에 걸려 있다."),
            (16, "사용자가 노트북 덮개를 들어 올리고 책상 위 충전 케이블을 연결한다."),
            (32, "화면에 글자와 작은 창들이 떠 있다. 사용자가 책상에서 키보드를 두드린다."),
        ])
    elif day.n % 3 == 0:
        scene(day, t, "거실", [
            (0, "사용자가 소파 옆 바구니에서 얇은 책 한 권을 꺼낸다."),
            (16, "사용자가 소파에 앉아 무릎 위에 책을 펼친다."),
            (40, "거실 소파에 앉은 사용자의 무릎에 책이 펼쳐져 있다."),
        ])
    else:
        scene(day, t, "거실", [
            (0, "사용자가 소파 옆에 쌓인 수건을 낮은 탁자에 올린다."),
            (20, "사용자가 펼친 수건을 반으로 접고 다른 수건 위에 포갠다."),
            (100, "접힌 수건이 탁자에 쌓여 있다. 사용자가 소파에 기대어 휴대전화를 본다."),
        ])


def build(day):
    rng = day.rng
    alarm = 8 * 3600
    late = day.work in {"휴일", "휴가"} and day.n in {7, 20, 28}
    if late:
        wake = alarm + 60 * rng.choice([7, 12, 16])
    else:
        earliest, latest = {"출근": (6 * 60 + 36, 7 * 60 + 3),
                            "재택": (7 * 60 + 2, 7 * 60 + 20),
                            "휴일": (7 * 60 + 10, 7 * 60 + 25),
                            "휴가": (7 * 60 + 10, 7 * 60 + 25)}[day.work]
        wake = 60 * rng.randint(earliest, latest)
    wake += 4 * rng.randrange(12)
    wake_up(day, wake)
    hair = day.n in {2, 6, 9, 14, 17, 21, 25, 28}
    start = wake + 4 * rng.randrange(96, 152) + (240 if hair else 0)
    finish = breakfast(day, start, hair)
    if late:
        prepare = finish + 60
    else:
        prepare = alarm + 4 * rng.randrange(2, 31)
        if finish >= alarm:
            raise ValueError("아침 식사와 고정 생활 알림이 겹침")
    medicine(day, alarm, prepare)
    if day.work == "출근":
        packing = alarm + 60 * rng.randrange(16, 46) + 4 * rng.randrange(15)
        leave_home(day, packing)
    else:
        at_home(day, prepare + 4 * rng.randrange(65, 146))
