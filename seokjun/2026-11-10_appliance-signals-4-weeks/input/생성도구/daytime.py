def build(day):
    if day.work == "출근":
        return
    quiet(day, time_at(9, 52))
    if day.n in LAUNDRY_DAYS:
        laundry(day)
    lunch(day)
    if day.work != "재택" or day.n == 24:
        exercise(day)
    afternoon(day)
    quiet(day, time_at(17, 12))
