LAUNDRY_DAYS = {3, 6, 10, 13, 17, 21, 24, 27}


def time_at(hour, minute=0):
    return hour * 3600 + minute * 60


def scene(day, start, location, changes):
    for offset, description in changes:
        day.see(start + offset, location, description)


def quiet(day, t):
    if day.work == "재택":
        day.see(t, "작업방", "책상 위에서 노트북 화면이 켜져 있다. 사용자가 의자에 앉아 있다.")
    else:
        room, description = day.rng.choice([
            ("거실", "사용자가 소파 팔걸이에 등을 기대고 휴대전화 화면을 보고 있다."),
            ("거실", "소파 앞 탁자에 펼쳐진 책이 있고 사용자가 그 앞에 앉아 있다."),
            ("작업방", "책상 위에 노트와 연필이 놓여 있고 사용자가 의자에 앉아 있다."),
        ])
        day.see(t, room, description)


