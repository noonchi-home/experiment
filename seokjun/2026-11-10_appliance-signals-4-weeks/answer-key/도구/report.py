"""기계 채점과 같은 행에서 사람이 읽을 날짜별 정답을 만든다."""
from collections import Counter, defaultdict
from pathlib import Path

from source import ROOT, load_jsonl


def group(rows):
    days = defaultdict(list)
    for row in rows:
        days[row["날짜"]].append(row)
    return days


def description(rule):
    if not rule["활성"]:
        return "—"
    parts = []
    for path in rule["활성"]:
        condition = " · ".join(f"{k} {v}" for k,v in path["조건"].items())
        parts.append(" ".join(filter(None,(path.get("시각","사건 발생"),condition))))
    return " 또는 ".join(parts)


def ratio(s):
    return f"{s['함']}/{s['분모']}" if s["분모"] else "근거 0건"


def table(rows):
    lines = ["| 시각 | 판단 | 맡을 일 | 그 시점의 근거 |","|---|---|---|---|"]
    for r in rows:
        reason = r["이유"]
        cite = r["근거"]
        where = f"관찰 {cite['관찰줄']:,}행" if "관찰줄" in cite else "해당 시각에 관찰 없음"
        extra = " 뒤의 자연기록에서는 사람이 실행하지 않았음." if any(
            "오개입 후보" in x["사후대조"] for x in r["세부"]) else ""
        lines.append(f"| {r['시각']} | **{r['예상판정']}** | {r['행동']} | {reason} ({where}){extra} |")
    return "\n".join(lines)


def write_day(folder, day, previous, tomorrow, states, decisions):
    blocks = [f"# {day} 밤의 예상 정답",
              "[28일 전체 안내로 돌아가기](../예상정답_읽는법.md)"]
